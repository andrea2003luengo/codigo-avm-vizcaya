def imputar_floor_cascada(df_datos, df_referencia):
    """
    Rellena los nulos de 'floor' utilizando una jerarquía de medianas:
    Barrio -> Distrito -> Municipio -> General (flats).
    """
    df_resultado = df_datos.copy()

    # Marcador para auditoría (1 = imputado, 0 = original)
    df_resultado['floor_estimated'] = df_resultado['floor'].isna().astype(int)

    def calcular_mediana_cascada(fila):
        muni, dist, barri, subtipo = fila['municipality'], fila['district'], fila['neighborhood'], fila['subTypology']

        # Nivel 1: Municipio + Distrito + Barrio + subTypology
        sub = df_referencia[(df_referencia['municipality'] == muni) &
                            (df_referencia['district'] == dist) &
                            (df_referencia['neighborhood'] == barri) &
                            (df_referencia['subTypology'] == subtipo)]['floor'].dropna()
        if not sub.empty: return sub.median()

        # Nivel 2: Municipio + Distrito + subTypology
        sub = df_referencia[(df_referencia['municipality'] == muni) &
                            (df_referencia['district'] == dist) &
                            (df_referencia['subTypology'] == subtipo)]['floor'].dropna()
        if not sub.empty: return sub.median()

        # Nivel 3: Municipio + subTypology
        sub = df_referencia[(df_referencia['municipality'] == muni) &
                            (df_referencia['subTypology'] == subtipo)]['floor'].dropna()
        if not sub.empty: return sub.median()

        # Nivel 4: Salvavidas para 'flat'
        general = df_referencia[df_referencia['propertyType'] == 'flat']['floor'].dropna()
        return general.median() if not general.empty else 0

    # Aplicación de la lógica
    def aplicar_imputacion(fila):
        if pd.notna(fila['floor']):
            return fila['floor']
        return int(np.round(calcular_mediana_cascada(fila)))

    df_resultado['floor'] = df_resultado.apply(aplicar_imputacion, axis=1)
    df_resultado['floor'] = df_resultado['floor'].astype('Int64')

    return df_resultado

