todos_los_predictores = ['ElasticNet', 'RandomForest', 'LightGBM', 'XGBoost']


for id_exp, config in dict_experimentos.items():
    # Segmentación asimétrica de los ecosistemas (train)
    df_premium_tr = df_meta_train_base[df_meta_train_base['propertyType'].isin(config['premium_types'])]
    df_urbano_tr = df_meta_train_base[~df_meta_train_base['propertyType'].isin(config['premium_types'])]

    # Generación de pipelines para el Nivel 1
    def get_pipe(params, alg):
        if alg == 'Ridge':
            return Pipeline([('s', StandardScaler()), ('ridge', Ridge(**params, positive=True, random_state=42))])
        if alg == 'Lasso':
            return Pipeline([('s', StandardScaler()), ('lasso', Lasso(**params, positive=True, random_state=42, max_iter=5000))])
        return Pipeline([('s', StandardScaler()), ('elastic', ElasticNet(**params, positive=True, random_state=42, max_iter=5000))])

    # Función objetivo unificada para Optuna
    def obj(trial, data):
        if config['algoritmo'] == 'Ridge':
            p = {'alpha': trial.suggest_float('alpha', 1e-3, 100.0, log=True)}
        elif config['algoritmo'] == 'Lasso':
            p = {'alpha': trial.suggest_float('alpha', 1e-4, 10.0, log=True)}
        else:
            p = {'alpha': trial.suggest_float('alpha', 1e-3, 100.0, log=True),
                 'l1_ratio': trial.suggest_float('l1_ratio', 0.0, 1.0)}

        pipe = get_pipe(p, config['algoritmo']).fit(data[todos_los_predictores], data['y_true'])
        return np.sqrt(mean_squared_error(data['y_true'], pipe.predict(data[todos_los_predictores])))

    # Optimización bayesiana cruzada de segmentos mediante Optuna
    optuna.logging.set_verbosity(optuna.logging.WARNING)
    est_u = optuna.create_study(direction='minimize', sampler=optuna.samplers.TPESampler(seed=42))
    est_u.optimize(lambda t: obj(t, df_urbano_tr), n_trials=30)

    est_p = optuna.create_study(direction='minimize', sampler=optuna.samplers.TPESampler(seed=42))
    est_p.optimize(lambda t: obj(t, df_premium_tr), n_trials=30)

    # Entrenamiento definitivo de meta-modelos especializados
    meta_u = get_pipe(est_u.best_params, config['algoritmo']).fit(df_urbano_tr[todos_los_predictores], df_urbano_tr['y_true'])
    meta_p = get_pipe(est_p.best_params, config['algoritmo']).fit(df_premium_tr[todos_los_predictores], df_premium_tr['y_true'])

    # Enrutamiento asimétrico definitivo sobre test
    df_meta_test = df_meta_test_base.copy()
    f_urb = ~df_meta_test['propertyType'].isin(config['premium_types'])

    df_meta_test.loc[f_urb, 'Pred'] = meta_u.predict(df_meta_test.loc[f_urb, todos_los_predictores])
    df_meta_test.loc[~f_urb, 'Pred'] = meta_p.predict(df_meta_test.loc[~f_urb, todos_los_predictores])

    # Evaluación e informe del escenario
