def extraer_datos_parking(valor):
    # Si la celda es nula, no tiene parking
    if pd.isna(valor):
        return False, False, 0.0

    # Si ya es un diccionario (JSON parseado)
    if isinstance(valor, dict):
        return valor.get('hasParkingSpace', False), valor.get('isParkingSpaceIncludedInPrice', False), valor.get('parkingSpacePrice', 0.0)

    # Si es una cadena de texto (formato JSON como string)
    if isinstance(valor, str):
        try:
            diccionario = ast.literal_eval(valor.strip())
            return diccionario.get('hasParkingSpace', False), diccionario.get('isParkingSpaceIncludedInPrice', False), diccionario.get('parkingSpacePrice', 0.0)
        except:
            # Búsqueda manual si falla el eval
            tiene_parking = "hasParkingSpace': True" in valor
            esta_incluido = "isParkingSpaceIncludedInPrice': True" in valor
            precio = 0.0
            if "parkingSpacePrice" in valor:
                try:
                    precio = float(valor.split("parkingSpacePrice':")[-1].split("}")[0].strip())
                except:
                    precio = 0.0
            return tiene_parking, esta_incluido, precio

    return False, False, 0.0

# Aplicamos la extracción a df1
