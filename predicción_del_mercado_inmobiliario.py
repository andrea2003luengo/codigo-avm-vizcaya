# Definición del objetivo de optimización
def objetivo_xgb(trial):
    params = {
        'objective': 'reg:squarederror',
        'eval_metric': 'rmse',
        'n_estimators': trial.suggest_int('n_estimators', 100, 500, step=50),
        'learning_rate': trial.suggest_float('learning_rate', 0.01, 0.15, log=True),
        'max_depth': trial.suggest_int('max_depth', 4, 10),
        'min_child_weight': trial.suggest_int('min_child_weight', 1, 10),
        'subsample': trial.suggest_float('subsample', 0.6, 0.9),
        'colsample_bytree': trial.suggest_float('colsample_bytree', 0.6, 0.9),
        'alpha': trial.suggest_float('alpha', 1e-3, 10.0, log=True),
        'lambda': trial.suggest_float('lambda', 1e-3, 10.0, log=True),
        'random_state': 42,
        'n_jobs': -1
    }

    cv_rmse_log_interno = []

    for train_idx, val_idx in folds_estratificados_fijos:
        X_tr, X_val = X_train_modelar.iloc[train_idx], X_train_modelar.iloc[val_idx]
        y_tr, y_val = y_train_log.iloc[train_idx], y_train_log.iloc[val_idx]

        model = xgb.XGBRegressor(**params)
        model.fit(X_tr, y_tr)

        preds_log = model.predict(X_val)
        rmse = np.sqrt(mean_squared_error(y_val, preds_log))
        cv_rmse_log_interno.append(rmse)

    return np.mean(cv_rmse_log_interno)

