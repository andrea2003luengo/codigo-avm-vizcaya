"""#### 2.7) Codificación de las variables categóricas/booleanas

Se van a aplicar las siguientes codificaciones:
*   **Target encoding:** A variables con muchas categorías y sin orden (municipality, district y neighborhood)
*   **One-hot encoding:** A variables con un número de categorías limitado y sin orden (propertyType, subTypology, status y highlight)
*   **Codificar a 0/1:** A variables booleanas (exterior, showAddress, hasVideo, hasLift, hasPlan, has3DTour, has360, hasStaging, haveParkingSpace y isParkingIncluded)
"""

# =====================================================================
# PASO 1: Codificación de variables categóricas y booleanas (train/test)
# =====================================================================

# Definición de bloques según la codificación a aplicar
cols_target_encoding = ['municipality', 'district', 'neighborhood']
cols_one_hot_encoding = ['propertyType', 'subTypology', 'status', 'highlight']
cols_booleanas = X_train_full.select_dtypes(include=['boolean', 'bool']).columns.tolist()

# Duplicación segura de matrices
X_train_encoded = X_train_full.copy()
X_test_encoded = X_test.copy()

# Conversión de booleanos a binario (0/1)
print("Convirtiendo variables booleanas a formato binario (0/1)...")
for col in cols_booleanas:
    X_train_encoded[col] = X_train_encoded[col].astype(int)
    X_test_encoded[col] = X_test_encoded[col].astype(int)

# One-Hot Encoding (Variables con categorías limitadas)
print("Aplicando One-Hot Encoding (baja cardinalidad)...")
# CORRECCIÓN: Se actualiza handle_unknown='value' para compatibilidad con versiones recientes de category_encoders
ohe = ce.OneHotEncoder(cols=cols_one_hot_encoding, use_cat_names=True, handle_unknown='value')
X_train_encoded = ohe.fit_transform(X_train_encoded)
X_test_encoded = ohe.transform(X_test_encoded)

# Target Encoding (Variables geográficas de alta cardinalidad)
print("Aplicando Target Encoding jerárquico (variables geográficas)...")
te = ce.TargetEncoder(cols=cols_target_encoding, handle_unknown='value')
X_train_encoded = te.fit_transform(X_train_encoded, y_train_log)
X_test_encoded = te.transform(X_test_encoded)

# Consolidación final y transformación de superficie
X_train_modelar = X_train_encoded.select_dtypes(include=[np.number]).copy()
X_test_modelar = X_test_encoded.select_dtypes(include=[np.number]).copy()

print("Transformando superficie a escala logarítmica ('size_log') y eliminando original...")
X_train_modelar['size_log'] = np.log1p(X_train_modelar['size'])
X_test_modelar['size_log'] = np.log1p(X_test_modelar['size'])

X_train_modelar = X_train_modelar.drop(columns=['size'])
X_test_modelar = X_test_modelar.drop(columns=['size'])

# Reporte final de integridad
print("-" * 68)
print(f"Matrices codificadas:")
print(f"  Conjunto train (X_train_modelar) ➔ {X_train_modelar.shape}")
print(f"  Conjunto test  (X_test_modelar)  ➔ {X_test_modelar.shape}")
print("-" * 68)
print(f"Nulos residuales post-proceso: Train: {X_train_modelar.isna().sum().sum()} | Test: {X_test_modelar.isna().sum().sum()}")

"""## Paso 3: Entrenamiento de los modelos

#### 3.1) MODELO BASE: Regresión lineal regularizada (*ElasticNet*)
"""

# ====================================================================
# PASO 1: Búsqueda de hiperparámetros mediante Grid Search
# ====================================================================

# Definimos la estructura del pipeline lineal
pipeline_base = Pipeline([
    ('scaler', StandardScaler()),
    ('model', ElasticNet(random_state=42, max_iter=20000))
])

# Configuración de la rejilla de parámetros
param_grid = {
    'model__alpha': [0.001, 0.01, 0.1, 1.0],
    'model__l1_ratio': [0.1, 0.3, 0.5, 0.7, 0.9]
}

# Búsqueda de hiperparámetros (Grid Search) con los folds estartificados
estrato_train = X_train_full['propertyType']
folds_estratificados_fijos = list(cv_estratificado.split(X_train_modelar, estrato_train))

grid_search = GridSearchCV(
    estimator=pipeline_base,
    param_grid=param_grid,
    cv=folds_estratificados_fijos,
    scoring='neg_mean_squared_error',
    n_jobs=-1
)

# Ajustamos el Grid Search para encontrar la mejor combinación paramétrica
grid_search.fit(X_train_modelar, y_train_log)

# Reporte de resultados
print("-" * 68)
print(f"Configuración óptima de hiperparámetros encontrada:")
for param, valor in grid_search.best_params_.items():
    print(f"    *{param.split('__')[1]}: {valor}")
print("-" * 68)

# Extracción del pipeline ganador
pipeline_lineal = grid_search.best_estimator_

# =====================================================================
# PASO 2: Evaluación mediante validación cruzada (5 folds)
# =====================================================================

cv_train_rmse_log = []
cv_val_rmse_log = []
cv_mae_euros = []

# Iteración sobre los folds definidos
for fold, (train_idx, val_idx) in enumerate(folds_estratificados_fijos, 1):
    X_tr, X_val = X_train_modelar.iloc[train_idx], X_train_modelar.iloc[val_idx]
    y_tr, y_val = y_train_log.iloc[train_idx], y_train_log.iloc[val_idx]

    # Entrenamiento del pipeline ganador en el fold actual
    pipeline_lineal.fit(X_tr, y_tr)

    # Predicciones
    preds_train_log = pipeline_lineal.predict(X_tr)
    preds_val_log = pipeline_lineal.predict(X_val)

    # Cálculo de RMSE en escala logarítmica
    rmse_train = np.sqrt(mean_squared_error(y_tr, preds_train_log))
    rmse_val = np.sqrt(mean_squared_error(y_val, preds_val_log))
    cv_train_rmse_log.append(rmse_train)
    cv_val_rmse_log.append(rmse_val)

    # Cálculo de MAE en euros (reversión de escala)
    preds_val_euros = np.expm1(preds_val_log)
    y_val_euros = np.expm1(y_val)
    mae_val_fold = mean_absolute_error(y_val_euros, preds_val_euros)
    cv_mae_euros.append(mae_val_fold)

    # Reporte por fold con formato legible
    mae_formateado = f"{mae_val_fold:,.2f}".replace(",", "X").replace(".", ",").replace("X", ".")
    print(f"Fold {fold}: RMSE val (log): {rmse_val:.4f} | MAE val: {mae_formateado} €")

# =====================================================================
# PASO 3: Evaluación de desempeño en test set
# =====================================================================

# Ajuste final con el conjunto completo de entrenamiento
pipeline_lineal.fit(X_train_modelar, y_train_log)

# Predicción y transformación a escala original
test_preds_log = pipeline_lineal.predict(X_test_modelar)
test_preds_euros = np.expm1(test_preds_log)
y_test_euros = np.expm1(y_test_log)

# Cálculo de métricas
test_rmse_log = np.sqrt(mean_squared_error(y_test_log, test_preds_log))
test_mae_euros = mean_absolute_error(y_test_euros, test_preds_euros)

# Formateo y presentación de resultados
print("====================================================================")
print("Resultados finales: Modelo base (ElasticNet)")
print("====================================================================")
print(f"RMSE medio (CV - log):           {np.mean(cv_val_rmse_log):.4f} (± {np.std(cv_val_rmse_log):.4f})")
print(f"RMSE final en test (log):        {test_rmse_log:.4f}")
print("-" * 68)
print(f"MAE medio (CV - euros):          {np.mean(cv_mae_euros):,.2f} €".replace(',', 'X').replace('.', ',').replace('X', '.'))
print(f"MAE final en test (euros):       {test_mae_euros:,.2f} €".replace(',', 'X').replace('.', ',').replace('X', '.'))

