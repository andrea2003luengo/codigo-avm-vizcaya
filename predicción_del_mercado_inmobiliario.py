    p_type = str(fila['propertyType'])
    d_type = str(fila['detailedType'])

    # Si es nulo, devolvemos el tipo base
    if pd.isna(d_type) or d_type.lower() == 'nan':
        return p_type

    try:
        # Convertimos la cadena string (representación de dict) a diccionario real
        dict_obj = ast.literal_eval(d_type)

        # Si el diccionario tiene 'subTypology', la extraemos
        if 'subTypology' in dict_obj:
            return dict_obj['subTypology']

        # Si no tiene 'subTypology', devolvemos el tipo base
        return p_type

    except (ValueError, SyntaxError):
        # En caso de error en el parseo, devolvemos el tipo base como salvaguarda
        return p_type

