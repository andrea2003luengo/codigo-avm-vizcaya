nombres_modelos = []
rmses_log = []
maes_euros = []
r2_scores = []

for nombre, preds_log in predicciones_log.items():
    # Cómputo de métricas síncronas por modelo
    rmse_log = np.sqrt(mean_squared_error(y_test_log.values, preds_log))
    preds_euros = np.expm1(preds_log)
    mae_euros = mean_absolute_error(y_true_euros, preds_euros)
    r2_neto = r2_score(y_true_euros, preds_euros)

    nombres_modelos.append(nombre)
    rmses_log.append(rmse_log)
    maes_euros.append(mae_euros)
    r2_scores.append(r2_neto * 100)  # Expresado en formato porcentual (%)

# Construir la tabla maestra de resultados (Ordenada por mejor MAE de forma ascendente)
