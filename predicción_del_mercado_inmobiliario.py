    params = {
        'n_estimators': trial.suggest_int('n_estimators', 100, 400, step=50),
        'max_depth': trial.suggest_int('max_depth', 8, 18),
        'min_samples_split': trial.suggest_int('min_samples_split', 2, 8),
        'min_samples_leaf': trial.suggest_int('min_samples_leaf', 1, 4),
        'max_features': trial.suggest_float('max_features', 0.5, 0.9),
        'random_state': 42,
        'n_jobs': -1
    }

    cv_rmse_log_interno = []

    for train_idx, val_idx in folds_estratificados_fijos:
        X_tr, X_val = X_train_modelar.iloc[train_idx], X_train_modelar.iloc[val_idx]
